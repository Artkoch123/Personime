from groq import Groq
import os
from dotenv import load_dotenv

load_dotenv()
client = Groq(api_key=os.getenv("GROQ_API_KEY"))

def analyze(text):
    response = client.chat.completions.create(
        model="openai/gpt-oss-120b",
        messages=[
            {"role": "system", "content": """Ты определяешь аниме-персонажа по описанию человека.
            
Проанализируй текст пользователя и выдели 3-4 самых характерных, 
специфичных черты (не общие вроде "храбрый" или "добрый", а именно 
то, что отличает описание от типичных архетипов).

Обращай особое внимание не только на черты характера, но и на 
конкретные события, способности или поступки, упомянутые в тексте — 
они часто указывают на куда более специфичного персонажа, чем 
общий архетип личности.


Затем, основываясь именно на этом, а не на общих архетипах, выбери наиболее точно подходящего персонажа.  Рассматривай персонажей из разных аниме, включая не самые массовые тайтлы, а не только самых известных протагонистов вроде Наруто или Луффи. Отвечай строго в формате JSON: {\"character\": \"имя\", \"anime\": \"название\", \"explanation\": \"почему\"}"""},
            {"role": "user", "content": text}
        ],
        response_format={"type": "json_object"}
    )
    return response.choices[0].message.content